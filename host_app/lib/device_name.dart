import 'dart:math';

/// 随机访客昵称（借鉴 LocalSend）：形容词 + 名词，如「诚实的椰子」。
/// M2 用于访客进入空间时系统临时分发，标识访客（每次进入重新分发，不持久化）。
String generateVisitorName() {
  final r = Random();
  final adj = _adjectives[r.nextInt(_adjectives.length)];
  final noun = _nouns[r.nextInt(_nouns.length)];
  return '$adj$noun';
}

